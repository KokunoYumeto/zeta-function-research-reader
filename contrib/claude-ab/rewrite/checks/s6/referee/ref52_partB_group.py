def orbit_partition(gens, D):
    n = D**3
    parent = list(range(n))
    def find(i):
        while parent[i] != i:
            parent[i] = parent[parent[i]]; i = parent[i]
        return i
    def idxp(b, cc, d): return (b % D)*D*D + (cc % D)*D + (d % D)
    for b in range(D):
        for cc in range(D):
            for d in range(D):
                v = [1, b, cc, d]
                for g in gens:
                    wv = [sum(g[i][j]*v[j] for j in range(4)) for i in range(4)]
                    assert wv[0] % D == 1 % D
                    ra, rb = find(idxp(b, cc, d)), find(idxp(wv[1], wv[2], wv[3]))
                    if ra != rb: parent[ra] = rb
    return [find(i) for i in range(n)]
