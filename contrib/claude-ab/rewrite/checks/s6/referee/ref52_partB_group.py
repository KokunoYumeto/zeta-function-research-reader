def ab_euclid(M):
    """abelianization SL2(Z) -> Z/12 with ab(T) = 1, ab(S) = 9, via Euclidean reduction over Z."""
    M = [row[:] for row in M]; acc = 0      # invariant: original = X * M_current, acc = ab(X)
    while M[1][0] != 0:
        a, c = M[0][0], M[1][0]
        k = -(a // c) if c != 0 else 0      # T^k M has top-left a + k c, reduced mod c
        M = [[M[0][0] + k*M[1][0], M[0][1] + k*M[1][1]], [M[1][0], M[1][1]]]; acc -= k   # M_old = T^-k M_new
        # now swap with S: M_new = S M  =>  M_old = S^-1 M_new
        M = [[-M[1][0], -M[1][1]], [M[0][0], M[0][1]]]; acc -= 9
    # M = [[e, b], [0, e]], e = +-1
    e, b = M[0][0], M[0][1]
