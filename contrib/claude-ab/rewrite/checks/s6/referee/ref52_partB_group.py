def inv_unimodular4(A):
    # exact inverse via adjugate (det = +-1 for all our matrices)
    import fractions
    n = 4
    M = [[fractions.Fraction(A[i][j]) for j in range(n)] + [fractions.Fraction(1 if i == j else 0) for j in range(n)] for i in range(n)]
    for col in range(n):
        piv = next(r for r in range(col, n) if M[r][col] != 0)
        M[col], M[piv] = M[piv], M[col]
        pv = M[col][col]
        M[col] = [x / pv for x in M[col]]
        for r in range(n):
            if r != col and M[r][col] != 0:
                f = M[r][col]
                M[r] = [a - f*b for a, b in zip(M[r], M[col])]
    Inv = [[M[i][n+j] for j in range(n)] for i in range(n)]
    assert all(x.denominator == 1 for row in Inv for x in row)
    return [[int(x) for x in row] for row in Inv]
