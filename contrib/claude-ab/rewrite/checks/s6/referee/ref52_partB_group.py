def word_for_sl2(M):
    """return a list of (symbol, exponent) with product = M, symbols 'S', 'T', 'Z' (= -I = S^2)."""
    M = [row[:] for row in M]; left = []     # original = product(left) * M_current
    while M[1][0] != 0:
        a, cc = M[0][0], M[1][0]
        k = -(a // cc)
        M = [[M[0][0] + k*M[1][0], M[0][1] + k*M[1][1]], [M[1][0], M[1][1]]]; left.append(('T', -k))
        M = [[-M[1][0], -M[1][1]], [M[0][0], M[0][1]]]; left.append(('S', -1))
    e, b = M[0][0], M[0][1]
    if e == 1: left.append(('T', b))
    else: left.append(('Z', 1)); left.append(('T', -b))
    return left
