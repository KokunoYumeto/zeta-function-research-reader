@functools.lru_cache(maxsize=None)
def Omega(n):
    """Number of prime factors with multiplicity (a completely additive function)."""
    return sum(sp.factorint(n).values())


def formal_log(members):
    """Exact coefficients r_n of log(sum_{n in M} e_n), for a finite initial segment of M.

    Uses the derivation D = Omega (completely additive): Omega(n) d_n = sum_{ab=n} Omega(a) r_a d_b,
    with d = indicator of M. The recursion is exact over the rationals."""
    members = sorted(members)
    S = set(members)
    r = {}
    for n in members:
        if n == 1:
            continue
        acc = Fraction(0)
        for a in members:
            if a == 1 or a >= n:
                continue
            if n % a == 0 and (n // a) in S:
                acc += Omega(a) * r[a]
        r[n] = 1 - acc / Omega(n)
    return r


def monoid_elements(gens, bound):
    elems = {1}
    frontier = [1]
    while frontier:
        new = []
        for x in frontier:
            for g in gens:
                y = x * g
                if y <= bound and y not in elems:
                    elems.add(y)
                    new.append(y)
        frontier = new
    return elems


def atoms_of(elems):
    E = sorted(elems)
    S = set(E)
    at = []
    for n in E:
        if n == 1:
            continue
        if not any(n % a == 0 and (n // a) in S and a != 1 and a != n for a in E if a < n):
            at.append(n)
    return at


def factorizations(n, atoms, start=0):
    """Unordered atom factorizations of n (atoms sorted)."""
    if n == 1:
        return [[]]
    out = []
    for i in range(start, len(atoms)):
        a = atoms[i]
        if a > n:
            break
        if n % a == 0:
            for rest in factorizations(n // a, atoms, i):
                out.append([a] + rest)
    return out


