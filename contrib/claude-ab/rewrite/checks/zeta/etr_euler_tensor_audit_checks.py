def W_block(omega, m, n):
    N = np.diag(np.ones(m - 1), -1)  # multiplication by epsilon on C[e]/(e^m) in the basis 1, e, ..., e^{m-1}
    E = np.zeros((m, m), dtype=complex)
    P = np.eye(m)
    for a in range(m):
        E += (math.log(n) ** a / math.factorial(a)) * P
        P = P @ N
    return (n ** omega) * E


def block_diag(mats):
    D = sum(M.shape[0] for M in mats)
    out = np.zeros((D, D), dtype=complex)
    i = 0
    for M in mats:
        k = M.shape[0]
        out[i:i + k, i:i + k] = M
        i += k
    return out


