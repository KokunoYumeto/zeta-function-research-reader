def minimal_generators(gens):
    """Atoms of the exponent semigroup generated by gens (the minimal generating set)."""
    g_sorted = sorted(set(gens))
    atoms_ = []
    for g_ in g_sorted:
        # g_ is not an atom if it is a sum of >= 2 nonzero elements of the semigroup generated by the smaller atoms
        reach = {0}
        frontier = {0}
        while frontier:
            new = set()
            for x_ in frontier:
                for a_ in atoms_:
                    y_ = x_ + a_
                    if y_ <= g_ and y_ not in reach:
                        reach.add(y_)
                        new.add(y_)
            frontier = new
        if g_ not in reach:
            atoms_.append(g_)
    return atoms_


